import assert from 'node:assert/strict';
import {MotionIntelligence} from './motion-intelligence.js';
const d=new MotionIntelligence({autoIdleEnabled:true,allowTalkInterruptions:true,thinkingDelay:0,speakingDelay:0,idleDelay:0});
let a=d.decide({now:0,state:'idle'});assert.equal(a.id,'idle');assert(d.commit(a,0));
assert.equal(d.decide({now:1,state:'idle',activeId:'idle',active:true}),null);
a=d.decide({now:2,state:'listening'});assert.equal(a?.id,'listening','Escuchando reproduce Head Gesture y NO Idle');assert(d.commit(a,2));
a=d.decide({now:3,state:'thinking'});assert.equal(a.id,'thinking');assert(d.commit(a,3));
assert.equal(d.decide({now:4,state:'thinking',activeId:'thinking',active:true}),null);
assert.equal(d.decide({now:6,state:'thinking'}),null,'Tras Thinking no reproducir Idle en automático');
d.setCircleEnabled(true);a=d.decide({now:7.2,state:'thinking',activeId:'idle',active:true});assert.equal(a.id,'walkingcircle');assert(d.commit(a,7.2));
assert.equal(d.decide({now:8,state:'thinking',activeId:'walkingcircle',active:true}),null);
a=d.decide({now:9,state:'speaking'});assert.equal(a.id,'talking');assert(d.commit(a,9));
a=d.decide({now:10.4,state:'speaking',activeId:'talking',active:true,emotion:{emotion:'happy',intensity:.75}});assert.equal(a.id,'happy');assert(d.commit(a,10.4));
a=d.decide({now:11,state:'speaking',activeId:'happy',active:true,emotion:{emotion:'happy',intensity:.75}});assert.equal(a,null);
a=d.decide({now:11.5,state:'speaking',active:false,emotion:{emotion:'happy',intensity:.75}});assert.equal(a.id,'talking');assert(d.commit(a,11.5));
assert.equal(d.decide({now:12,state:'speaking',activeId:'talking',active:true,emotion:{emotion:'happy',intensity:.75}}),null);
a=d.decide({now:23,state:'speaking',activeId:'talking',active:true});assert(['pointinggesture','pointing','thinking'].includes(a.id));assert(d.commit(a,23));
const oldRevision=d.revision;d.observe('idle',24);assert(d.revision>oldRevision);
assert.equal(d.commit(a,25),false,'intención obsoleta descartada');
d.postpone(25,1.2);assert.equal(d.decide({now:25.5,state:'idle'}),null);
assert.equal(d.decide({now:26.3,state:'idle'}).id,'idle');
d.setEnabled(false);assert.equal(d.decide({now:30,state:'speaking'}),null);
d.setEnabled(true);assert.equal(d.decide({now:31,state:'speaking'}).id,'talking');
d.setVariety(0);assert.equal(d.variety,0);d.setVariety(200);assert.equal(d.variety,100);
const noWalk=new MotionIntelligence();noWalk.decide({now:0,state:'thinking'});noWalk.commit({id:'thinking',revision:noWalk.revision,reason:'x'},0);
assert.notEqual(noWalk.decide({now:10,state:'thinking'})?.id,'walkingcircle');
console.log('Motion Intelligence: 24 comprobaciones funcionales y transiciones PASS');
