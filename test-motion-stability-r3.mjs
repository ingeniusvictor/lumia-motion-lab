import assert from 'node:assert/strict';
import fs from 'node:fs';
import {MotionIntelligence} from './motion-intelligence.js';
import {findMicroSpikeSteps,repairQuaternionMicroSpikes} from './motion-clip-stability.js';
import {BodyPresenceCore} from './body-presence.js';
const angleQ=deg=>[0,0,Math.sin(deg*Math.PI/360),Math.cos(deg*Math.PI/360)];
const track={name:'J_Bip_R_LowerArm.quaternion',times:Float32Array.from([0,.033333,.066666,.100000,.103333,.106666,.110000,.113333,.133333,.166666]),values:Float32Array.from([0,1,3,5,74,-6,6,6,8,9].flatMap(angleQ)),getValueSize(){return 4;}};
const raw=Array.from(track.values);
const suspect=findMicroSpikeSteps(track.times,track.values);
assert(suspect.length>=2,'debe detectar microtirones en la curva');
const clip={tracks:[track]};
const report=repairQuaternionMicroSpikes(clip);
assert(report.spikeCount>=2&&report.segments>=1,'debe corregir al menos un segmento');
assert(findMicroSpikeSteps(track.times,track.values).length===0,'debe eliminar picos microscópicos');
assert.notDeepEqual(Array.from(track.values),raw);
const director=new MotionIntelligence({idleDelay:0,speakingDelay:0});
assert.equal(director.autoIdleEnabled,true);
assert.equal(director.decide({now:0,state:'idle'}).id,'idle');
assert.equal(director.decide({now:1,state:'listening',active:true,activeId:'idle'})?.id,'listening');
let i=director.decide({now:2,state:'speaking'});assert.equal(i.id,'talking');assert(director.commit(i,2));
assert.equal(director.decide({now:20,state:'speaking',active:true,activeId:'talking',emotion:{emotion:'happy',intensity:1}}),null,'Talking NO se interrumpe por default');
director.setAllowTalkInterruptions(true);
assert.equal(director.decide({now:21,state:'speaking',active:true,activeId:'talking',emotion:{emotion:'happy',intensity:1}}).id,'happy','modo experimental opcional');
const p=new BodyPresenceCore();
for(let t=0;t<150;t++)p.step(1/60,{behavior:'idle',enabled:true,idleLevel:65,listeningLevel:80});
for(let t=0;t<180;t++)p.step(1/60,{behavior:'listening',enabled:true,idleLevel:65,listeningLevel:80});
const listening=p.step(1/60,{behavior:'listening',enabled:true,idleLevel:65,listeningLevel:80});
assert(listening.listeningWeight>.99);
assert(Math.abs(listening.offsets.chestX*180/Math.PI)>2,'escucha corporal apreciable');
assert(Math.abs(listening.offsets.leftUpperArmZ*180/Math.PI)>2.5,'brazos en postura distintiva de escucha');
const html=fs.readFileSync('./index.html','utf8'), viewer=fs.readFileSync('./viewer.js','utf8');
for(const id of ['stability-thinking','intelligence-talk-accents','intelligence-auto-idle'])assert(html.includes(`id="${id}"`));
assert(viewer.includes('repairQuaternionMicroSpikes(fixed.clip)'));
assert(viewer.includes("key==='thinking'&&stabilityConfig.repairThinking"));
console.log('R3: microtirones, escucha diferenciada, reposo FBX y Talking protegido PASS');
