import assert from 'node:assert/strict';
import {classifyGrapheme,textWords,TextVisemeTimeline,TimedVisemeTimeline,validateVisemeMarks,energyEnvelope} from './viseme-core.js';
import {analyzeEmotion} from './emotion-core.js';
import {ConversationController} from './conversation-core.js';

assert.equal(classifyGrapheme('á').vowel,'aa');
assert.equal(classifyGrapheme('u').vowel,'ou');
assert.equal(classifyGrapheme('m').amount,0);
assert.equal(textWords('Hola, ¿cómo estás?').length,3);
const timeline=new TextVisemeTimeline();
timeline.start('Hola, mundo.',1000);
timeline.boundary(0,1020);
assert.equal(timeline.cue(1020).vowel,'aa'); // H semiabierta
assert.equal(timeline.cue(1120).vowel,'oh');
assert.equal(timeline.cue(1220).vowel,'aa');
timeline.boundary(6,1420);
assert.equal(timeline.cue(1420).amount,0); // m bilabial
assert.equal(timeline.cue(1505).vowel,'ou');
timeline.stop();assert.equal(timeline.cue(1510),null);
const fallback=new TextVisemeTimeline();fallback.start('hola',0);assert.ok(fallback.cue(100));
const timed=new TimedVisemeTimeline();
timed.load([{timeMs:0,viseme:'sil',amount:0},{timeMs:100,viseme:'aa',amount:.7},{timeMs:300,viseme:'oh',amount:.6}]);
timed.start(1000);
assert.equal(timed.cue(1000).vowel,null);
assert.equal(timed.cue(1100).vowel,'aa');
assert.equal(timed.cue(1399).vowel,'oh');
assert.throws(()=>validateVisemeMarks([{timeMs:200,viseme:'aa'},{timeMs:100,viseme:'ee'}]));
assert.throws(()=>validateVisemeMarks([{timeMs:0,viseme:'INVALIDO'}]));
assert.equal(energyEnvelope(new Uint8Array(32).fill(128)),0);
assert.ok(energyEnvelope(new Uint8Array(32).fill(200))>.5);
assert.equal(analyzeEmotion('¡Enhorabuena, es maravilloso!').emotion,'happy');
assert.equal(analyzeEmotion('Lamento mucho la pérdida.').emotion,'sad');
assert.equal(analyzeEmotion('Probemos con calma.').emotion,'relaxed');
assert.equal(analyzeEmotion('Una explicación técnica neutral.').emotion,'neutral');
assert.equal(analyzeEmotion('Cualquier texto','surprised',.7).emotion,'surprised');
assert.equal(analyzeEmotion('Cualquier texto','Extra',.9).emotion,'neutral');
const c=new ConversationController();
let eventHistory=[];
c.subscribe((state,event)=>eventHistory.push(event.type));
let receiveRaw=null;
const ok=await c.submit('Hola',async()=>({reply:'¡Excelente!',emotion:'happy',intensity:.5}),async(text,id,raw)=>{receiveRaw=raw; c.setSpeaking();});
assert.equal(ok,true);assert.equal(receiveRaw.emotion,'happy');assert.equal(c.state,'speaking');
assert.ok(eventHistory.includes('message'));
let resolveA;
const pending=c.submit('A',()=>new Promise(r=>resolveA=r));
await Promise.resolve();
const next=c.submit('B',async()=>({reply:'B respondió'}));
await next;resolveA({reply:'A tardía'});assert.equal(await pending,false);
assert.ok(!c.history.some(x=>x.text==='A tardía'));
